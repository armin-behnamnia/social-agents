"""The variable registry: every metric this project records, with a description.

Single source of truth
----------------------
Three consumers read this module and therefore can never drift apart:

- ``code/live_monitor.py`` — renders the live dashboard and the
  ``/api/state`` payload; uses :data:`Field.hist`, :data:`Field.iter_agg`
  and :data:`Field.chart` to decide what to aggregate and plot;
- ``METRICS.md`` — generated by ``python code/metrics_registry.py``;
- ``code/tests/test_metrics_registry.py`` — asserts that every field the
  tracer writes is documented here (a new field with no description
  fails the suite).

Streams
-------
``iteration``  one record per PPO update, in ``training_log.json``
``eval``       the same file, fields added every ``--eval-every`` iters
``paired_eval``the same file, added every ``--paired-eval-every`` iters
``status``     derived by the monitor from the config + log timestamps
``steps``      ``trace/steps.jsonl``   — immediate per-decision variables
``periods``    ``trace/periods.jsonl`` — per-period population state
``events``     ``trace/events.jsonl``  — per-hop diffusion events
``episodes``   ``trace/episodes.jsonl``— per-episode summaries
``strategy``   ``strategy_value.json`` — per-arm value table

Reward decomposition (arms)
---------------------------
One ``reward`` per persuader per period is the sum of the terms below;
the training reward is the team mean of it. Keep this in mind when
reading any reward chart: the arms differ in which terms are non-zero.

===================  =================================================
term                 meaning
===================  =================================================
stance movement      ``-Δs`` summed over events the persuader sourced
                     (negative delta = target moved toward the persuader)
accept shaping       ``shaping_accept_bonus`` per ``accept``/``emerge``
adoption bonus       ``reward_adoption_bonus`` per newly adopted target
goal alignment       ``PERSUASION_GOAL_LAMBDA · a(m)`` per delivered message
message cost         ``message_cost`` per delivered message (default 0)
cascade discount     ``reward_cascade_discount · Δ(population mean stance)``
                     shared by the whole team (counterfactual credit)
===================  =================================================
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Any, Iterable


@dataclass(frozen=True)
class Field:
    """One recorded variable.

    name      key/path as written (dotted for nested iteration records)
    stream    which trace/record it belongs to
    kind      num | cat | str | id | flag | ts | list
    desc      what it means, in words — the point of this module
    unit      measurement unit / range, for axis labels and humans
    hist      (lo, hi, bins) → the monitor keeps a histogram (values
              outside the range land in the edge bins)
    iter_agg  aggregate per iteration (mean for num, sum for counts) so
              immediate variables can be charted against the training
              curve
    chart     plottable as a per-iteration series in the dashboard
    """

    name: str
    stream: str
    kind: str
    desc: str
    unit: str = ""
    hist: tuple[float, float, int] | None = None
    iter_agg: bool = False
    chart: bool = False


def _f(name, stream, kind, desc, unit="", hist=None, iter_agg=False, chart=False):
    return Field(name, stream, kind, desc, unit, hist, iter_agg, chart)


