def fields_for(stream: str) -> tuple[Field, ...]:
    return STREAMS[stream]


def field_map(stream: str) -> dict[str, Field]:
    return {f.name: f for f in STREAMS[stream]}


def get(name: str, stream: str | None = None) -> Field:
    """Look a field up by name (optionally within one stream)."""
    if stream is not None:
        return field_map(stream)[name]
    for candidate in STREAMS.values():
        for f in candidate:
            if f.name == name:
                return f
    raise KeyError(name)


def chart_fields(stream: str) -> tuple[Field, ...]:
    return tuple(f for f in STREAMS[stream] if f.chart)


def flatten_record(record: dict[str, Any], prefix: str = "") -> dict[str, Any]:
    """Flatten a nested record into dotted paths (lists stay as lists)."""
    flat: dict[str, Any] = {}
    for key, value in record.items():
        path = f"{prefix}{key}"
        if isinstance(value, dict):
            flat.update(flatten_record(value, prefix=f"{path}."))
        else:
            flat[path] = value
    return flat


def history_series(
    history: Iterable[dict[str, Any]], name: str
) -> list[tuple[int, float]]:
    """Extract an exact (iteration, value) series for a dotted metric name."""
    out: list[tuple[int, float]] = []
    for rec in history:
        flat = flatten_record(rec)
        value = flat.get(name)
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            continue
        out.append((int(rec.get("iteration", len(out) + 1)), float(value)))
    return out


